#!/usr/bin/env python3
"""Build the 64-bit port as a native macOS arm64 executable.

Runs on the Mac, after the Linux guest-base build (build_boot.py --arch 64
--guest-base 0x200000000, in Docker) has written
pc/build/boot64-gb/macos_manifest.json: every linked object in link order,
its compile command, the edits made to it (section and symbol renames) and
the data imports' addresses. Each object gets a Mach-O twin compiled by the
Mac's clang from the same input, the ELF edits translated:

- symbol renames (objcopy --redefine-sym) become -D old=new for the unit,
  which renames its definitions and references alike;
- section renames (game state, overlay statics) become a
  `#pragma clang section` at the top of the unit, with short Mach-O names
  (16 characters at most) recorded in macos_sections.json;
- static functions made global (--globalize-symbol) lose their `static`.

Usage: build_macos.py                 compile every unit (report.txt lists failures)
       build_macos.py --only link     generated objects, SDL 3, link pc/build/macos/rood
       build_macos.py --only game|host|generated
Run from the repository root of a Mac; play with
  pc/build/macos/rood --skip-movies   (ROOD_RENDERER=gl: Apple's OpenGL 4.1)
"""
import argparse
import concurrent.futures
import json
import os
import pathlib
import re
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "pc/tools"))
import guest_base as guest_base_tool  # noqa: E402

TARGET = "arm64-apple-macos14.0"
# gcc flags with no clang meaning (or a different one), dropped from commands.
DROP = {"-m64", "-m32", "-fpie", "-fno-pie", "-fno-pic", "-no-pie", "-fpermissive", "-mno-direct-extern-access",
        "-fkeep-static-functions", "-fgnu89-inline", "-fno-gnu-unique", "-MD"}
DROP_PREFIX = ("-gz", "-Werror", "-mcmodel", "-fcf-protection", "-MF", "-MT", "-march", "-mtune",
               "-ftrivial-auto-var-init", "-msse", "-mavx", "-mfpmath", "-mfma", "-mf16c")
# Host units: Darwin's spellings of what the Linux sources use, and the
# headers Linux finds in the system (OpenGL as <GL/gl.h>, Vulkan's headers,
# which SDL 3 vendors; the loader is reached through SDL at run time).
HOST_DARWIN = ["-D_DARWIN_C_SOURCE", "-D_XOPEN_SOURCE=700", "-Dst_mtim=st_mtimespec",
               "-Ipc/macos/include", "-Ipc/third_party/SDL3/src/video/khronos",
               "-include", "pc/macos/include/mac_compat.h",
               "-include", "pc/build/macos/include/mac_sections.h"]
# ELF section bounds the sources name (__start_X/__stop_X) that no edit
# creates: the game's code range of the Linux layout (absent here: empty).
EXTRA_SECTIONS = {"rood_game_text": "__TEXT"}


def section_table(manifest, table):
    """Short Mach-O names for every renamed section, assigned in a fixed
    order before any unit compiles (the pragmas and mac_sections.h agree)."""
    names = set(EXTRA_SECTIONS)
    for edits in manifest["edits"].values():
        names.update(edits_of(edits)[1].values())
    for name in sorted(names):
        short_section(name, table)


def write_section_header(table, path):
    """mac_sections.h: __start_X/__stop_X as ld64's section$start/section$end."""
    lines = ["/* Generated by build_macos.py: ELF section bounds as ld64's section$start/end symbols. */",
             "#pragma once"]
    for name, short in sorted(table.items()):
        if not re.fullmatch(r"\w+", name):
            continue
        segment = EXTRA_SECTIONS.get(name, "__DATA")
        lines.append(f'extern char __rood_start_{name}[] __asm__("section$start${segment}${short}");')
        lines.append(f'extern char __rood_stop_{name}[] __asm__("section$end${segment}${short}");')
        lines.append(f"#define __start_{name} __rood_start_{name}")
        lines.append(f"#define __stop_{name} __rood_stop_{name}")
    path.write_text("\n".join(lines) + "\n")
# Diagnostics clang makes errors where gcc warns (the decompiled C relies on
# gcc's leniency): warnings, as on Linux.
LENIENT = ["-Wno-error", "-Wno-implicit-function-declaration", "-Wno-int-conversion",
           "-Wno-incompatible-pointer-types", "-Wno-int-to-pointer-cast", "-Wno-return-type",
           "-Wno-incompatible-function-pointer-types", "-w"]


def short_section(name, table):
    """A Mach-O section name (16 characters at most) for an ELF one."""
    if name not in table:
        table[name] = f"__rd{len(table):04d}"
    return table[name]


def translate(command, source):
    """The clang flags of a recorded gcc/g++ command, without its input,
    output, -c and dependency options."""
    out, skip = [], False
    for a in command[1:]:
        if skip:
            skip = False
            continue
        if a in ("-o", "-MF", "-MT"):
            skip = True
            continue
        if a == "-c" or a == source or a in DROP or a.startswith(DROP_PREFIX):
            continue
        out.append(a)
    return out


def edits_of(edits):
    renames, sections, exposed = {}, {}, set()
    for args in edits:
        for a in args:
            key, _, value = a.partition("=")
            if key == "--redefine-sym":
                old, new = value.split("=")
                renames[old] = new
            elif key == "--rename-section":
                old, new = value.split("=")
                sections[old] = new
            elif key == "--globalize-symbol":
                exposed.add(value)
    return renames, sections, exposed


def pragma(sections, table):
    """#pragma clang section for the unit's renamed .data/.bss."""
    data = {new for old, new in sections.items() if old.startswith(".data")}
    bss = {new for old, new in sections.items() if old.startswith(".bss")}
    parts = []
    if data:
        parts.append(f'data="__DATA,{short_section(sorted(data)[0], table)}"')
    if bss:
        parts.append(f'bss="__DATA,{short_section(sorted(bss)[0], table)}"')
    return f"#pragma clang section {' '.join(parts)}\n" if parts else ""


def unexpose(text, names):
    for name in names:
        text = re.sub(rb"\bstatic\s+((?:inline\s+)?[\w\s\*]*\b" + re.escape(name.encode()) + rb"\s*\()",
                      rb"\1", text)
    return text


# Game units are preprocessed on Linux: what differs on Darwin is patched in
# their text. __builtin_setjmp/longjmp do not exist on arm64 Darwin: libc's
# _setjmp/_longjmp (no signal mask either) with its larger buffer.
DARWIN_PRELUDE = (b"extern int __rood_setjmp(void*) __asm__(\"__setjmp\") __attribute__((returns_twice));\n"
                  b"extern void __rood_longjmp(void*, int) __asm__(\"__longjmp\") __attribute__((noreturn));\n")


def darwin_text(data, table):
    data = data.replace(b"__builtin_setjmp(", b"__rood_setjmp(").replace(b"__builtin_longjmp(", b"__rood_longjmp(")
    # boot_sdk.c's buffers (and main.c's declarations): libc's jmp_buf size.
    data = re.sub(rb"((?:extern )?void\* pc_(?:title|battle)_jump)\[5\]", rb"\1[32]", data)
    # Assembler names given to C declarations (__asm__("CompMatrixLV")):
    # Mach-O's C symbols carry a leading underscore.
    data = re.sub(rb'__asm__\s*\(\s*"([A-Za-z]\w*)"\s*\)', rb'__asm__("_\1")', data)
    # ELF section names (no segment): a Mach-O __DATA section each.
    return re.sub(rb'section\s*\(\s*"([^",]+)"\s*\)',
                  lambda m: b'section("__DATA,' + short_section(m.group(1).decode(), table).encode() + b'")', data)


def declare_before_use(data, names):
    """clang rejects a definition that conflicts with an earlier implicit
    declaration (gcc warns): declare each such function before its first
    use, with its definition's own signature."""
    for name in names:
        n = re.escape(name.encode())
        definition = re.search(rb"^([\w \t\*]+?\b" + n + rb"\s*\([^;{)]*\))\s*\{", data, re.M)
        first = re.search(rb"\b" + n + rb"\s*\(", data)
        if not definition or not first or first.start() >= definition.start():
            continue
        line = data.rfind(b"\n", 0, first.start()) + 1
        data = data[:line] + definition.group(1) + b"; " + data[line:]
    return data


def compile_game(obj, command, edits, out, table, base):
    """A game unit: its rewritten .i, patched for Darwin and for the ELF
    edits (pragma sections, renames, exposed statics)."""
    source = next(a for a in command if a.endswith(".i"))
    renames, sections, exposed = edits_of(edits)
    data = (root / source).read_bytes() if not os.path.isabs(source) else pathlib.Path(source).read_bytes()
    data = DARWIN_PRELUDE + pragma(sections, table).encode() + darwin_text(unexpose(data, exposed), table)
    # Preprocessed input takes no -D: the renames (objcopy --redefine-sym on
    # Linux) apply to the text, definitions and references alike.
    if renames:
        pattern = re.compile(rb"\b(" + b"|".join(re.escape(o.encode()) for o in renames) + rb")\b")
        data = pattern.sub(lambda m: renames[m.group(1).decode()].encode(), data)
    twin_source = out / (pathlib.Path(obj).stem + ".mac.i")
    target = out / (pathlib.Path(obj).stem + ".o")
    args = ["clang", "-target", TARGET, "-c", str(twin_source), "-o", str(target),
            *translate(command, source), *LENIENT]
    for _ in range(3):
        twin_source.write_bytes(data)
        result = subprocess.run(args, cwd=root, capture_output=True, text=True)
        conflicts = re.findall(r"conflicting types for '(\w+)'", result.stderr)
        if not result.returncode or not conflicts:
            break
        data = declare_before_use(data, conflicts)
    return target, result


def preprocessed_flags(flags):
    """The flags left for compiling preprocessed text: no defines, include
    paths or forced includes (-include takes the next argument)."""
    out, skip = [], False
    for f in flags:
        if skip:
            skip = False
        elif f in ("-include", "-isystem", "-iquote"):
            skip = True
        elif not f.startswith(("-D", "-I", "-U", "-include", "-isystem", "-iquote")):
            out.append(f)
    return out


def compile_host(obj, command, edits, out, table, base):
    """A host unit (pc/src, third-party): compiled from its source against
    macOS's headers; a C unit gets the guest-base rewrite on its preprocessed
    text, as on Linux (build_boot.py guest_base_host)."""
    source = next(a for a in command[1:] if a.endswith((".c", ".C", ".cpp", ".cc")))
    cxx = command[0] in ("g++", "c++") or source.endswith((".cpp", ".cc"))
    renames, sections, exposed = edits_of(edits)
    # No NRD on macOS: vk_nrd.cpp builds its stub.
    flags = [f for f in translate(command, source) if f != "-DROOD_NRD" and "/nrd" not in f]
    flags += HOST_DARWIN + [f"-D{o}={n}" for o, n in renames.items()]
    target = out / (pathlib.Path(obj).stem + ".o")
    compiler = "clang++" if cxx else "clang"
    # .c built as C++ (Lua), or psycross's .C built as C (gcc -std=gnu11).
    language = ["-x", "c++"] if cxx and source.endswith(".c") else ["-x", "c"] if source.endswith(".C") else []
    prefix = pragma(sections, table)
    # Preprocessed here, then patched as text (ELF section names, and for C
    # the guest-base rewrite); C++ gets no rewrite (guest_base.py reads C).
    pre = out / (pathlib.Path(obj).stem + (".mac.ii" if cxx else ".mac.i"))
    if "psycross" in source or "gte" in pathlib.Path(source).stem:
        # psycross's PS1 types (u_long) clash with Darwin's BSD types, which
        # _DARWIN_C_SOURCE and the compat header bring in: plain POSIX here.
        plain, skip = [], False
        for i, f in enumerate(flags):
            if skip:
                skip = False
            elif f == "-include" and flags[i + 1:i + 2] == ["pc/macos/include/mac_compat.h"]:
                skip = True
            elif f != "-D_DARWIN_C_SOURCE":
                plain.append(f)
        flags = plain
    cpp = subprocess.run([compiler, "-target", TARGET, *language, "-E", source, "-o", str(pre), *flags, *LENIENT],
                         cwd=root, capture_output=True, text=True)
    if cpp.returncode:
        return target, cpp
    data = pre.read_bytes()
    if base and not cxx:
        data = guest_base_tool.rewrite(data, base, target="arm64-apple-macos14.0")[0]
    pre.write_bytes(prefix.encode() + darwin_text(data, table))
    args = [compiler, "-target", TARGET, *(["-x", "c++-cpp-output"] if cxx else []), "-c", str(pre), "-o", str(target),
            *preprocessed_flags(flags), *LENIENT]
    return target, subprocess.run(args, cwd=root, capture_output=True, text=True)


FRAMEWORKS = ["Cocoa", "IOKit", "CoreAudio", "AudioToolbox", "CoreVideo", "Carbon", "ForceFeedback",
              "GameController", "Metal", "QuartzCore", "CoreHaptics", "UniformTypeIdentifiers",
              "AVFoundation", "CoreMedia", "OpenGL"]


def compile_generated(linux_out, out, table):
    """The objects build_boot.py generates without a recorded command:
    native_imports (LP64 pointer tables, aliases as Mach-O assignments),
    overlay_statics_table (section bounds through mac_sections.h) and the
    data imports as absolute symbols."""
    results = []
    text = (linux_out / "native_imports.c").read_text()
    text = re.sub(r'__asm__\("\.globl (\w+)\\n\.type \w+, @object\\n\.set \w+, (\w+) \+ (\d+)"\);',
                  r'__asm__(".globl _\1\\n_\1 = _\2 + \3");', text)
    for name, text in [("native_imports", text),
                       ("overlay_statics_table", (linux_out / "overlay_statics_table.c").read_text())]:
        source = out / f"{name}.mac.c"
        source.write_bytes(darwin_text(text.encode(), table))
        results.append((name, subprocess.run(
            ["clang", "-target", TARGET, "-O2", "-fno-common", "-c", str(source), "-o", str(out / f"{name}.o"),
             "-include", "pc/build/macos/include/mac_sections.h", *LENIENT],
            cwd=root, capture_output=True, text=True)))
    return results


def write_imports(imports, out):
    """The data imports at their guest addresses (base included), absolute."""
    source = out / "imports.s"
    source.write_text("".join(f".globl _{name}\n_{name} = {address:#x}\n" for name, address in sorted(imports.items())))
    return subprocess.run(["clang", "-target", TARGET, "-c", str(source), "-o", str(out / "imports.o")],
                          cwd=root, capture_output=True, text=True)


def build_sdl(out):
    """SDL 3 (vendored) as a static arm64 library, once."""
    library = out / "sdl3/libSDL3.a"
    if library.exists():
        return
    subprocess.run(["cmake", "-S", "pc/third_party/SDL3", "-B", str(out / "sdl3"), "-G", "Ninja",
                    "-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_OSX_ARCHITECTURES=arm64",
                    "-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0", "-DSDL_SHARED=OFF", "-DSDL_STATIC=ON",
                    "-DSDL_TESTS=OFF", "-DSDL_TEST_LIBRARY=OFF", "-DSDL_EXAMPLES=OFF", "-DSDL_INSTALL=OFF",
                    "-DSDL_CAMERA=OFF", "-DSDL_GPU=OFF", "-DSDL_RENDER_GPU=OFF", "-DSDL_VULKAN=ON",
                    "-DSDL_RENDER_VULKAN=OFF"], cwd=root, check=True, capture_output=True)
    subprocess.run(["ninja", "-C", str(out / "sdl3")], cwd=root, check=True, capture_output=True)


def link(manifest, out):
    build_sdl(out)
    objects = [str(out / (pathlib.Path(o).stem + ".o")) for o in manifest["objects"]]
    objects += [str(out / "native_imports.o"), str(out / "imports.o")]
    seen, ordered = set(), []
    for o in objects:  # traps and overlay_statics_table are listed once
        if o not in seen:
            seen.add(o)
            ordered.append(o)
    args = ["clang++", "-target", TARGET, "-o", str(out / "rood"), *ordered,
            str(out / "sdl3/libSDL3.a"), *[a for f in FRAMEWORKS for a in ("-framework", f)],
            "-liconv", "-lc++",
            # Weak references nothing defines (the engine library's hooks):
            # null at run time, as an undefined weak symbol is on ELF.
            "-Wl,-undefined,dynamic_lookup"]
    (out / "link_command.json").write_text(json.dumps(args) + "\n")
    # The runtime writes its diagnostic frames to ROOD_OUT, by default
    # pc/build/boot (on Linux pc/run-game.sh's build makes it).
    (root / "pc/build/boot").mkdir(parents=True, exist_ok=True)
    return subprocess.run(args, cwd=root, capture_output=True, text=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", choices=["game", "host", "generated", "link"])
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    args = parser.parse_args()
    manifest = json.loads((root / "pc/build/boot64-gb/macos_manifest.json").read_text())
    out = root / "pc/build/macos"
    out.mkdir(parents=True, exist_ok=True)
    table_path = out / "macos_sections.json"
    table = json.loads(table_path.read_text()) if table_path.exists() else {}
    section_table(manifest, table)
    (out / "include").mkdir(exist_ok=True)
    write_section_header(table, out / "include/mac_sections.h")

    def local(arg):
        # The manifest's paths are the container's (/work = the repository).
        return arg.replace("/work/", "")

    if args.only in ("generated", "link"):
        linux_out = root / "pc/build/boot64-gb"
        for name, result in compile_generated(linux_out, out, table) + [("imports", write_imports(manifest["imports"], out))]:
            print(f"{name}: {'ok' if not result.returncode else result.stderr[-3000:]}")
        if args.only == "link":
            result = link(manifest, out)
            print("link: " + ("ok, " + str(out / "rood") if not result.returncode else result.stderr[-6000:]))
            return result.returncode
        return 0
    jobs, results = [], []
    for obj in manifest["objects"]:
        command = manifest["commands"].get(obj)
        if command is None:
            continue
        command = [local(a) for a in command]
        edits = manifest["edits"].get(obj, [])
        is_game = any(a.endswith(".i") for a in command)
        is_host = not is_game and any(a.endswith((".c", ".C", ".cpp", ".cc")) for a in command[1:])
        if (args.only == "game" and not is_game) or (args.only == "host" and not is_host):
            continue
        if is_game or is_host:
            jobs.append((compile_game if is_game else compile_host, obj, command, edits))
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = {pool.submit(fn, obj, command, edits, out, table, manifest["guest_base"]): obj
                   for fn, obj, command, edits in jobs}
        for future in concurrent.futures.as_completed(futures):
            target, result = future.result()
            results.append((futures[future], result))
    table_path.write_text(json.dumps(table, indent=1) + "\n")
    failed = [(o, r) for o, r in results if r.returncode]
    report = out / "report.txt"
    with report.open("w") as f:
        for o, r in sorted(failed):
            f.write(f"== {o}\n{r.stderr}\n")
    print(f"{len(results) - len(failed)} of {len(results)} units compiled; failures in {report}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
